export function applyMonacoTheme(theme: AppTheme): void {
  ensureTheme();
  monaco.editor.setTheme(monacoThemeId(theme));
}

export function editorOptions(settings: Settings): monaco.editor.IStandaloneEditorConstructionOptions {
  return {
    theme: monacoThemeId(currentAppTheme()),
    automaticLayout: true,
    fontFamily: editorFontStack(settings),
    fontSize: settings["editor.fontSize"],
    fontLigatures: settings["editor.fontLigatures"],
    lineHeight: lineHeightFor(settings["editor.lineHeight"], settings["editor.fontSize"]),
    tabSize: settings["editor.tabSize"],
    insertSpaces: true,
    detectIndentation: false,
    minimap: { enabled: settings["editor.minimap"], renderCharacters: false, maxColumn: 90 },
    wordWrap: settings["editor.wordWrap"] ? "on" : "off",
    lineNumbersMinChars: 4,
    glyphMargin: true,
    folding: true,
    showFoldingControls: "mouseover",
    bracketPairColorization: { enabled: true },
    guides: { bracketPairs: true, indentation: true, highlightActiveBracketPair: true },
    renderWhitespace: "selection",
    renderControlCharacters: false,
    cursorBlinking: "smooth",
    cursorSmoothCaretAnimation: "on",
    smoothScrolling: true,
    scrollBeyondLastLine: false,
    padding: { top: 8, bottom: 8 },
    fixedOverflowWidgets: true,
    quickSuggestions: { other: true, comments: false, strings: false },
    suggestOnTriggerCharacters: true,
    parameterHints: { enabled: true },
    formatOnPaste: false,
    formatOnType: false,
    multiCursorModifier: "alt",
    links: true,
    colorDecorators: true,
    accessibilitySupport: "auto",
    ariaLabel: t("editor.codeEditorAria"),
    scrollbar: {
      verticalScrollbarSize: 10,
      horizontalScrollbarSize: 10,
      useShadows: false,
    },
    overviewRulerBorder: false,
    hideCursorInOverviewRuler: false,
    stickyScroll: { enabled: true },
  };
}

export function applyEditorOptions(
  editor: monaco.editor.IStandaloneCodeEditor,
  settings: Settings,
): void {
  editor.updateOptions(editorOptions(settings));
}
