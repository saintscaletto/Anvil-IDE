let themeRegistered = false;

export type MonacoThemeId = "anvil-dark" | "anvil-light" | "anvil-high-contrast";

export function monacoThemeId(theme: AppTheme): MonacoThemeId {
  switch (theme) {
    case "light":
      return "anvil-light";
    case "high-contrast":
      return "anvil-high-contrast";
    default:
      return "anvil-dark";
  }
}

